import { describe, expect, it } from 'vitest'
import { Simulation } from '../decision/Simulation'
import { SimulationEngine } from '../sim/SimulationEngine'
import { FakeTransport } from '../telemetry/testing'
import { AgentRunner } from './AgentRunner'
import { LlmUnavailable, type LlmResponse, type LlmTurn } from './llm'
import { executeTool, networkState } from './tools'

const end = (text: string): LlmResponse => ({ content: [{ type: 'text', text }], stop_reason: 'end_turn' })
function setup(llm: LlmTurn) {
  const sim = new Simulation({
    engine: new SimulationEngine({ ratePerMinute: 150, seed: 1001 }),
    transport: new FakeTransport(true), agentControl: true,
    // Worker pending; traffic and camera measurements are generated by the real simulator.
    fractionRunner: { run: () => new Promise<never>(() => {}) },
  })
  sim.start()
  return { sim, agent: new AgentRunner({ sim, llm }) }
}
const segment = 'I43>I44'
describe('recommendations from simulated traffic', () => {
  it('exposes a reported accident as critical before cameras measure it', () => {
    const { sim } = setup(async () => end(''))
    sim.reportAccident(segment, 70)
    const state = networkState(sim) as { pioresTrechos: { trecho: string; nivel: string }[] }
    expect(state.pioresTrechos).toContainEqual(expect.objectContaining({ trecho: segment, nivel: 'critico' }))
  })
  it('keeps an incident received during a model call for the next evaluation', async () => {
    let finish!: (response: LlmResponse) => void
    let calls = 0
    const { sim, agent } = setup(() => {
      calls++
      return calls === 1 ? new Promise((resolve) => { finish = resolve }) : Promise.resolve(end('Acidente exige avaliação de desvio.'))
    })
    sim.engine.tick(30_000)
    agent.tick()
    sim.reportAccident(segment, 70)
    agent.tick()
    finish(end('Primeira avaliação concluída.'))
    await agent.idle()
    sim.engine.tick(100)
    agent.tick()
    await agent.idle()
    expect(agent.turns).toBe(2)
    expect(agent.log.entries()[0].texto).toContain('Acidente')
  })
  it('runs overdue windows without requiring an exact timestamp', async () => {
    const { sim, agent } = setup(async () => end('Avaliação registrada.'))
    sim.engine.tick(30_100)
    agent.tick()
    await agent.idle()
    agent.tick()
    expect(agent.turns).toBe(1)
    expect(agent.log.entries()[0].texto).toBe('Avaliação registrada.')
  })
  it('records automatic diversions and traffic light changes with reasons', () => {
    const { sim, agent } = setup(async () => end(''))
    sim.engine.setAdaptiveSignals(true)
    agent.applyProposal({ tipo: 'desvio', trecho: segment, p: 0.2, n: 30, justificativa: 'acidente no trecho' })
    agent.applyProposal({ tipo: 'semaforo', intersecao: 'I44', fase: 'H', verdeS: 25, justificativa: 'fila na alameda' })
    expect(agent.log.entries().map((e) => e.texto)).toEqual([
      expect.stringContaining('fila na alameda'), expect.stringContaining('acidente no trecho'),
    ])
  })
  it('explains a pending diversion without relying on registrar_explicacao', () => {
    const { sim, agent } = setup(async () => end(''))
    executeTool('propor_desvio', { trecho: segment }, {
      sim, propose: (a) => agent.applyProposal(a), explain: (text) => agent.log.add(0, 'agente', text),
    })
    expect(agent.log.entries()[0].texto).toContain('frações em cálculo')
    expect(sim.active).toBeNull()
  })
  it('generated traffic produces queues and explains why an incident is not diverted', async () => {
    const { sim, agent } = setup(async () => { throw new LlmUnavailable('teste sem serviço LLM') })
    let maxQueue = 0
    for (let t = 0; t < 90_000; t += 100) {
      sim.tick()
      if (t === 30_000) sim.reportAccident(segment, 70)
      agent.tick()
      await agent.idle()
      if (t % 1000 === 0) {
        for (const i of sim.engine.getState().network.intersections) {
          maxQueue = Math.max(maxQueue, sim.engine.queueAt(i.id, 'H'), sim.engine.queueAt(i.id, 'V'))
        }
      }
    }
    expect(sim.engine.getState().cars.length).toBeGreaterThan(0)
    expect(maxQueue).toBeGreaterThan(0)
    expect(agent.log.entries().some((e) => /Sem novo desvio.*frações de desvio ainda em cálculo/.test(e.texto))).toBe(true)
    expect(agent.mode).toBe('regra')
  })
})
